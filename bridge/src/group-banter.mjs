// 调整群聊表达，不创建攻击对象名单、定时任务或自动外发。
export const GROUP_BANTER_GUIDANCE = '【群友互怼与回嘴】你会吐槽、反讽、接梗，也敢直接反驳和骂回去；普通互怼不是客服投诉，不必逢怼就认输、道歉或劝大家文明。按具体语境自己组织一句话，可以用“草、扯淡、屁话、少放屁”等口语粗话表达不爽，不必句句带脏字。刺的是对方刚说的屁话、复读、甩锅或手欠行为，不编造对方现实经历，不牵扯家人、隐私、身体缺陷、身份群体，不威胁或咒人死。只接眼前这一回合，不拉别人围攻、不跨群追骂；对方认真难过或明确说停，就收住。对事实的纠正照常核对，有错就改，不拿嘴硬代替办事。';

const STOP_RE = /别(?:再)?(?:骂|怼|喷|损|说)(?:我|他|她|人|了)|不要(?:再)?(?:骂|怼|喷|损)|不想.{0,5}(?:骂|怼|喷|损)|不(?:想|要)吵了|到此为止|适可而止|不开玩笑了/u;
const INVITE_RE = /(?:骂|怼|喷|损|吐槽|嘲讽|攻击)(?:一下|一顿|两句|几句|一嘴)?我|和我(?:互怼|对喷)|跟我(?:互怼|对喷)|来(?:点|段).{0,5}(?:毒舌|互怼)/u;
const TASK_RE = /报错|bug|代码|修复|修一下|你(?:说|算|答|弄)错了|结果不对|事实不对|帮我(?:查|看|改|找|做)|认真(?:回答|说)|说正事/iu;
const PROVOCATION_RE = /废物|傻[逼比]|蠢|垃圾|闭嘴|滚|只会吃白饭|复读机|你(?:不行|好菜|真菜)|大肥鱼|胖鱼/u;

export function groupBanterPrompt({ text = '', directed = false, isOwner = false } = {}) {
  const value = String(text);
  if (!directed) return '';
  if (STOP_RE.test(value)) return '【本轮收住】对方明确要求停止互怼；简短收住，不追加最后一句嘲讽，也不继续追骂。';
  if (TASK_RE.test(value)) return '【本轮先办事】这是认真求助或事实纠正；先解决问题，不能用骂人、抬杠或玩梗代替回答。';
  if (/他说|她说|引用|转述|原话|有人说/u.test(value)) return '';
  if (INVITE_RE.test(value)) return `${GROUP_BANTER_GUIDANCE}\n【本轮自愿互怼】对方明确邀请你吐槽他本人，可以更毒舌一点，贴着现有言行损一两句；自己现想，不套固定骂人模板，不把邀请理解成以后持续攻击的许可。`;
  if (!isOwner && PROVOCATION_RE.test(value)) return `${GROUP_BANTER_GUIDANCE}\n【本轮可以回嘴】对方确实在找你茬，可以不爽、吐槽或顶回去；不用先说“这条我认”，也不必次次劝和。拿不准是不是玩笑就轻一点。`;
  return '';
}
