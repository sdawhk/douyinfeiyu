const APPROVAL_PHRASES = new Set([
  '可以你去改吧', '可以去改', '好你去改吧', '好你改吧', '行你去改吧', '行你改吧',
  '那你去改吧', '你去改吧', '去改吧', '可以动手了', '你动手吧', '动手吧',
  '按这个改', '就按这个改', '就改这个', '直接改', '改吧', '这次你来改',
  '我给你重新授权', '我给你重新授权了', '我给你授权', '我给你授权了',
  '我重新授权你', '重新授权', '重新授权了', '已经授权', '已经授权了',
  '给你重新授权', '我真的给你授权', '我真的给你授权了'
]);

export function isProfileApproval(text) {
  const normalized = String(text ?? '').replace(/[\s，,。.!！?？、:：；;“”"‘’「」『』]/g, '');
  if (APPROVAL_PHRASES.has(normalized)) return true;
  return /^确认(?:改|修改)(?:(?:昵称|名称)(?:和|与)?(?:个性签名|签名)|(?:个性签名|签名)(?:和|与)?(?:昵称|名称))$/.test(normalized);
}
