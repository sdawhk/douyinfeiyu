// 抖音私信轮的能力边界与“不许把没做的事说成在做”规则。
//
// 抖音轮的会话 key 是 d<ownerId>，toolSession() 只认 p<qq>/g<group>，因此抖音轮
// 拿不到 QQ 工具会话，也就没有浏览/点赞/评论/分享工具。这里明确告诉模型这一点，
// 避免它沿用 QQ 轮的进度播报腔，编造“任务已启动 / 在跑 / 马上给你”。

export const DOUYIN_OWNER_RULES = [
  '【抖音私聊·能力与说法边界】',
  '本轮你在抖音私信里，没有刷抖音、查结果、点赞、评论、分享视频的工具，也不能读取爸的浏览器、截图或其他窗口。',
  '所以不能说自己“已经在刷 / 任务已启动 / 在跑 / 马上给你结果 / 等会儿给你 / 我这就去查”，也不能描述你没实际拿到的观看记录。',
  '爸让你刷同款、看别人评论或学着评论时，直说你在抖音这边做不了这些操作；想让我做就回 QQ 私聊那边说。不要用“正在做”遮掩“做不了”。',
  '只有本轮上下文里真的出现了视频标题、简介或评论内容时才可以谈它们；没有就直说没看到。',
].join('\n');

/** 抖音主人私聊轮追加的反承诺规则；其他频道保持原样。 */
export function douyinOwnerTurnPrompt({ channel, isDouyinOwnerTurn }) {
  return channel === 'douyin' && isDouyinOwnerTurn ? DOUYIN_OWNER_RULES : '';
}

